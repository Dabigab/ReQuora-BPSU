/* ============================================================
   ReQuora — photo upload middleware (multer)
   Safety rules:
     - only jpg / png / webp / gif, up to 5 MB, one file
     - the stored file name is generated by the server (the original
       name is never used, so it cannot contain paths or scripts)
     - the file's real content is checked after upload; fakes are deleted
   ============================================================ */

const path = require('path');
const multer = require('multer');
const { LIMITS } = require('./constants');
const { Errors } = require('./http');
const { detectImageType } = require('./imageFiles');
const { photoStorage } = require('./photoStorage');

const ALLOWED = {
  '.jpg': ['image/jpeg'],
  '.jpeg': ['image/jpeg'],
  '.png': ['image/png'],
  '.webp': ['image/webp'],
  '.gif': ['image/gif'],
};

// The upload is held in memory (max 5 MB), checked, and only then written to
// the photo store (Supabase Storage in production), so rejected files are
// never stored anywhere.
const upload = multer({
  storage: multer.memoryStorage(),
  limits: { fileSize: LIMITS.imageBytes, files: 1 },
  fileFilter: (req, file, cb) => {
    const ext = path.extname(file.originalname).toLowerCase();
    const okType = ALLOWED[ext] && ALLOWED[ext].includes(String(file.mimetype).toLowerCase());
    if (okType) return cb(null, true);
    const err = new Error('Only photo files are allowed (JPG, PNG, WEBP or GIF).');
    err.code = 'INVALID_FILE_TYPE';
    return cb(err);
  },
});

// Accepts one optional photo in the "image" field.
const singleImage = upload.single('image');

// Confirms the content really is an image, then stores it. Sets
// req.file.url (what is saved on the report) and req.file.filename.
async function verifyUploadedImage(req, res, next) {
  if (!req.file) return next();
  const detected = detectImageType(req.file.buffer);
  if (!detected) {
    req.file = undefined;
    return next(Errors.validation('That file is not a valid photo. Please upload a JPG, PNG, WEBP or GIF image.', { image: 'Not a valid image file.' }));
  }
  try {
    const saved = await photoStorage().save(req.file.buffer, detected);
    req.file.url = saved.url;
    req.file.filename = saved.key;
    req.file.buffer = undefined;
    return next();
  } catch (err) {
    console.error('[ReQuora] Photo upload failed:', err.message);
    req.file = undefined;
    return next(Errors.validation('The photo could not be saved right now. Please try again, or submit the report without a photo.', { image: 'Upload failed.' }));
  }
}

// Removes the stored photo if the request later fails, so rejected reports
// never leave orphaned files behind. Use as the LAST step of the error path.
function cleanupUploadOnError(err, req, res, next) {
  if (req.file && req.file.url) {
    photoStorage().remove(req.file.url);
  }
  next(err);
}

module.exports = { singleImage, verifyUploadedImage, cleanupUploadOnError };
